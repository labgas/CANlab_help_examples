% Run this script headless from the Linux command line (the default), which
% publishes the html report and fails loudly if the script errors:
%
%   labgascore_run_headless.sh -d /data/proj_xxx \
%       -s <proj>_secondlevel_m<M>_s0_a_set_up_paths_always_run_first \
%       <proj>_secondlevel_m<M>_s<N>_c2a_second_level_regression
%
% Or, interactively from the Matlab terminal (use this when you want
% higher-resolution figures, or are debugging):
%
%   LaBGAScore_prov_publish('c2a_second_level_regression', htmlsavedir)
%
% NOTE: publish() catches a script error into the html and returns normally, so
% a crashed run looks exactly like a successful one. Prefer the routes above,
% which read the report back and check for a caught error, over a bare
% publish('c2a_second_level_regression','outputDir',htmlsavedir).
% 
% See the documentation of prep_3a_run_second_level_regression_and_save.m
% for more info and options
%
%
% *OPTIONS FOR CURRENT SCRIPT*
% 
%   NOTE: 
%       defaults are specified in a2_set_default_options for any given model,
%       but if you want to run the same model with different options, 
%       you can make a copy of this script with a letter index (e.g. _s6a_) 
%       and change the default option below
%
% _GLM options_
%
% * save_figures_glm                true saves .svg files of all figures generated by c2a_second_level_regression.m (slow, takes up space)
%
% * q_threshold_glm                 threshold for FDR-corrected display items
%
% * p_threshold_glm                 threshold for uncorrected display items
%
% * k_threshold_glm                 extent threshold for both corrected and uncorrected display items
%
% * BF_threshold_glm                threshold for Bayes Factor maps, |BF| > 10 indicates strong evidence in favour of H1 (positive value) or H0 (negative value) - see help.statistic_image.estimateBayesFactor for details
%
%
% _TFCE display options_
%
%   NOTE:
%       these display the TFCE results computed by prep_3a; the options that
%       control the TFCE computation itself (doTFCE, perm_n_tfce, tfce_seed,
%       tfce_sidedness, tfce_tail, cons2tfce) are documented in prep_3a and are
%       read from the saved results here. TFCE is reported only for the
%       contrasts prep_3a actually computed it for.
%
% * tfce_correction                 'fwe' (default) or 'fdr': which multiple-comparisons correction to REPORT for TFCE. Both thresholded objects are saved by prep_3a; only the reported one gets montages and region tables
%
% * p_threshold_fwe                 threshold for the FWE-corrected TFCE p-values (default .05). These are ALREADY corrected, so they are applied uncorrected - putting FDR on top would correct twice
%
% * k_threshold_tfce                extent threshold for TFCE display items. Defaults to 0, and deliberately NOT to k_threshold_glm: TFCE already integrates cluster extent into the statistic, so an extent threshold on top of a voxelwise FWE correction corrects twice. Setting it to 50 has been observed to remove every surviving voxel of a genuine result
%
% * dotables_tfce_unc               false (default) skips region tables for the UNCORRECTED TFCE map, which typically covers tens of thousands of voxels and produces a table too long to read. The corrected map is always tabled
%
%
% _MVPA options_
%
% * dobootstrap_mvpa_reg_cov
%
%     mvpa bootstrapping options
%
%       * boot_n_mvpa_reg_cov           number of bootstrap samples
%       * mvpa_engine                   'legacy' (default) or 'predictive_model'.
%                                       EXCLUSIVE: selects which bootstrap runs,
%                                       never both. 'predictive_model' adds
%                                       stability selection alongside it.
%       * nstab_mvpa_reg_cov            stability-selection resamples; defaults to
%                                       boot_n_mvpa_reg_cov, which lets the engine
%                                       DERIVE stability from the bootstrap weights
%                                       already computed instead of refitting
%       * stab_threshold_mvpa_reg_cov   'stable' if selected in >= this fraction
%                                       of resamples; default 0.9. MUST exceed 0.5
%       * stab_EV_mvpa_reg_cov          target expected number of FALSE selections;
%                                       default 1. Used to derive stab_k
%       * stab_k_mvpa_reg_cov           top-k voxels by |w| per resample. Leave
%                                       EMPTY to derive it from the threshold and
%                                       stab_EV. See the note below before setting it
%
% *CHOOSING THE STABILITY-SELECTION THRESHOLD*
%
% Stability selection fits the model on many resamples, ranks features by |weight|
% on each, and records which land in the TOP k. A feature's SELECTION FREQUENCY is
% the fraction of resamples in which it made that cut; the THRESHOLD pi is the
% frequency above which it is called "stable".
%
% THE TWO KNOBS CANNOT BE CHOSEN SEPARATELY. Meinshausen & Buhlmann (2010) Thm 1
% bounds the expected number of falsely selected features:
%
%       E(V) <= k^2 / ((2*pi - 1) * p)
%
%   * k  - how permissive each single resample is
%   * pi - how consistent a feature must be across resamples
%   * p  - number of features (voxels in the analysis mask)
%
% Three consequences:
%
%   1. pi MUST EXCEED 0.5. At 0.5 the denominator is zero and the bound undefined;
%      below it, negative. pi = 0.6 is not wrong in principle but (2*pi-1) = 0.2
%      sits on the steep part of the curve - about 5x worse than pi = 0.9.
%
%   2. k ENTERS SQUARED, p ONLY LINEARLY. This is what breaks at brain scale. The
%      class default k = 2000 is roughly 20x a typical genetics-scale k, and that
%      penalty is squared, which the larger p does not offset. Measured at
%      p = 149154 (canlab2023 grey matter):
%
%           k        pi=0.6    pi=0.9
%           2000      134.1      33.5      <- the class default controls nothing
%            500        8.4       2.1
%            345        4.0       1.0
%
%      At k = 2000 NO valid pi reaches E(V) <= 1: the algebra demands pi >= 13.9.
%
%   3. SO INVERT THE FORMULA. Fix the false-selection budget you will tolerate and
%      let k follow:  k = sqrt((2*pi - 1) * p * E(V)).  At pi = 0.9, p = 149154,
%      E(V) = 1 this gives k = 345. That is what this script does when
%      stab_k_mvpa_reg_cov is left empty.
%
% Whichever route is taken, the implied E(V) is PRINTED, so a threshold never
% appears without its error characteristics. Setting k explicitly is allowed and
% reports the bound it implies; E(V) > 10 additionally warns and names the k that
% would give E(V) <= 1 at the chosen pi.
%
% CAVEAT TO STATE IN A METHODS SECTION. The theorem assumes SUBSAMPLING at n/2
% (complementary pairs). @predictive_model/stability_selection resamples WITH
% REPLACEMENT, as does the boot_w-reuse path in mvpa_reg_cov_predictive_model.
% Shah & Samworth (2013) derive the bound for that case and it differs. Treat the
% printed E(V) as the right order of magnitude, not an exact guarantee - which is
% why it is reported rather than silently trusted.
%
% References:
%   Meinshausen N, Buhlmann P (2010) Stability selection. JRSS-B 72:417-473.
%   Shah RD, Samworth RJ (2013) Variable selection with error control: another
%       look at stability selection. JRSS-B 75:55-80.
%
%       * parallelstr_mvpa_reg_cov      'parallel'/'noparallel'  
%
%       * cons2boot_mvpa_reg_cov        vector of indices of conditions/contrasts to bootstrap
%
%     mvpa thresholding options
%
%       * q_threshold_mvpa_reg_cov      threshold for fdr-corrected maps
%
%       * k_threshold_mvpa_reg_cov      extent threshold (in voxels)
%
%
% *OPTIONS TO COPY FROM CORRESPONDING PREP_3a_ SCRIPT*
%
% _Mandatory options_
%
